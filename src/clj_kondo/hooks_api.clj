(ns clj-kondo.hooks-api
  "The API clj-kondo hooks are written against, so a project's
  `.clj-kondo` hooks (and the ones libraries export) run in jolt-lsp.

  Nodes are rewrite-clj nodes. Their location is in their metadata
  ({:row :col :end-row :end-col}); a node without it was made by a hook."
  {:no-doc true}
  (:refer-clojure :exclude [resolve])
  (:require [clojure.string :as string]
            [rewrite-clj.node :as node]
            [rewrite-clj.parser :as parser]))

(def ^:dynamic *ctx*
  "Bound by jolt-lsp.hooks while a hook runs: {:findings atom :ns sym
  :aliases {str str} :refers {str str} :locals #{str} :heads [str]
  :filename str}."
  nil)

(def ^:dynamic *reload* false)

(defn- mark-generate [n]
  (assoc n :clj-kondo.impl/generated true))

(defn generated-node?
  "Checks whether node was generated by other hook, or if the node was
  written by user. Assumes that a node without location metadata was
  generated."
  [node]
  (or (:clj-kondo.impl/generated node)
      (let [m (meta node)]
        (or (:clj-kondo.impl/generated m)
            (not (:row m))))))

(defn node? [n]
  (satisfies? rewrite-clj.node.protocols/Node n))

(defn- whitespace? [n]
  (contains? #{:whitespace :newline :comma :comment} (node/tag n)))

(defn- strip-whitespace
  "clj-kondo's parser leaves whitespace out of :children; rewrite-clj's keeps it."
  [n]
  (if (seq (:children n))
    (assoc n :children (mapv strip-whitespace (remove whitespace? (:children n))))
    n))

(defn parse-string [s]
  (strip-whitespace (parser/parse-string s)))

(defn keyword-node? [n]
  (instance? rewrite_clj.node.keyword.KeywordNode n))

(defn keyword-node
  ([k] (mark-generate (node/keyword-node k)))
  ([k auto-resolved?] (mark-generate (node/keyword-node k auto-resolved?))))

(defn string-node? [n]
  (instance? rewrite_clj.node.stringz.StringNode n))

(defn string-node [s]
  (mark-generate (node/string-node s)))

(defn token-node? [n]
  (or (instance? rewrite_clj.node.token.TokenNode n)
      (instance? rewrite_clj.node.token.SymbolNode n)))

(defn token-node [v]
  (mark-generate (node/token-node v)))

(defn quote-node? [n]
  (instance? rewrite_clj.node.quote.QuoteNode n))

(defn quote-node [n]
  (mark-generate (node/quote-node n)))

(defn- seq-node-of? [t n]
  (and (instance? rewrite_clj.node.seq.SeqNode n)
       (identical? t (node/tag n))))

(defn vector-node? [n] (seq-node-of? :vector n))
(defn list-node? [n] (seq-node-of? :list n))
(defn set-node? [n] (seq-node-of? :set n))
(defn map-node? [n] (seq-node-of? :map n))

(defn vector-node [children] (mark-generate (node/vector-node children)))
(defn list-node [children] (mark-generate (node/list-node children)))
(defn set-node [children] (mark-generate (node/set-node children)))
(defn map-node [children] (mark-generate (node/map-node children)))

(defn sexpr [expr]
  (node/sexpr expr))

(defn tag [n]
  (node/tag n))

(defn reg-finding!
  "Report a finding: {:message :type :row :col :end-row :end-col :level}."
  [m]
  (when-let [a (:findings *ctx*)]
    (swap! a conj m))
  nil)

(defn reg-keyword!
  [k reg-by]
  (assoc k :reg reg-by))

(defn coerce [s-expr]
  (node/coerce s-expr))

(defn ns-analysis
  "clj-kondo answers from its cache; jolt-lsp's hooks run during the walk,
  before the index has another namespace's facts, so this is empty."
  ([_ns-sym] {})
  ([_ns-sym _opts] {}))

(defn resolve
  "{:ns sym :name sym} for a symbol as the current namespace reads it, or
  nil for a local or a name that does not resolve."
  [{:keys [name]}]
  (let [{:keys [ns aliases refers locals]} *ctx*
        s (str name)
        nsn (namespace name)
        nm (clojure.core/name name)]
    (cond
      (and (nil? nsn) (contains? locals s)) nil
      nsn {:ns (symbol (get aliases nsn nsn)) :name (symbol nm)}
      (contains? refers s) (let [t (get refers s)
                                 i (string/index-of t "/")]
                             {:ns (symbol (subs t 0 i)) :name (symbol (subs t (inc i)))})
      (contains? (ns-publics 'clojure.core) name) {:ns 'clojure.core :name name}
      ns {:ns ns :name name}
      :else nil)))

(defn env []
  (zipmap (map symbol (:locals *ctx*)) (repeat {})))

(defn callstack
  "The calls around the hooked one, innermost first: [{:ns :name}]."
  []
  (vec (for [h (reverse (:heads *ctx*))]
         (or (resolve {:name (symbol h)}) {:ns nil :name (symbol h)}))))
